import { chromium } from '@playwright/test';
const [url, dir, theme = 'light'] = process.argv.slice(2);
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, colorScheme: theme });
await page.goto(url);
await page.evaluate((t) => localStorage.setItem('juno.develog.theme', t), theme);
await page.reload();
const stage = page.locator('.race-stage');
await stage.scrollIntoViewIfNeeded();
await page.waitForTimeout(1500);
await stage.screenshot({ path: `${dir}/01-ready.png` });
await page.locator('.race-stage button', { hasText: '레이스 시작' }).first().click();
await page.waitForTimeout(5000);
await stage.screenshot({ path: `${dir}/02-race-early.png` });
await page.waitForTimeout(28000);
await stage.screenshot({ path: `${dir}/03-race-mid.png` });
await page.waitForFunction(() => /10 \/ 10 도착/.test(document.querySelector('.race-stage')?.innerText ?? ''), null, { timeout: 120000 });
await page.waitForTimeout(800);
await stage.screenshot({ path: `${dir}/04-result.png` });
await browser.close();
